/** Shared rules for generated choices (book adventures and Create Your Own). */
export const CHOICE_RULES = `Choices:
- 2 or 3 options, each at most 12 words, starting with a verb ("Follow the glowing footprints").
- Clearly different from each other: different directions, not three versions of the same idea.
- Every option is something a kind, curious or brave hero might do. Never cruel, never self-harm,
  never "kill" someone. Tricking, escaping, helping, exploring and talking are all great.
- No spoilers in the wording, and no "Do nothing" or "Go home" options.`;
