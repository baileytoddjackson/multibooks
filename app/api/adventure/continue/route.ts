import { z } from "zod";
import { loadAdventureBook } from "@/lib/adventure/bookContext";
import { beatIndexFor } from "@/lib/adventure/outline";
import { currentUser, unauthorized } from "@/lib/auth/session";
import { guardGeneration, ipHashFor, recordGeneration } from "@/lib/budget/budget";
import { env } from "@/lib/env";
import { sseResponse } from "@/lib/http/sse";
import { runGeneration } from "@/lib/llm/runGeneration";
import { buildAdventureContinuationPrompt } from "@/lib/prompts/adventure";
import { findBlocked } from "@/lib/safety/blocklist";
import { generatedTextIsClean } from "@/lib/safety/moderate";
import { MAX_FACTS } from "@/lib/schemas/userData";
import { serverStore } from "@/lib/server-store";
import { cleanGeneratedText as clean } from "@/lib/text/clean";

/**
 * POST /api/adventure/continue → text/event-stream (same event shapes as /api/adventure/start)
 *   ready: {story, summary, facts, choices, isEnding}
 *
 * Stateless, like Create Your Own: the client sends the adventure's running context (summary,
 * facts, choices so far, the last pages) from the saved story. All of it was generated by us, but
 * it passes through the browser, so it's length-limited and re-checked.
 */
const Text = (max: number) => z.string().max(max);
const BodySchema = z.object({
  bookId: z.string().regex(/^[a-z0-9-]{1,40}$/),
  summary: Text(1500),
  facts: z.array(Text(200)).max(MAX_FACTS),
  choicesSoFar: z.array(Text(200)).max(200),
  recentPages: z.array(Text(4000)).min(1).max(2),
  choice: Text(200).optional(),
  style: z.enum(["direct", "character", "both"]).optional(),
  characterId: z
    .string()
    .regex(/^[a-z0-9-]{1,60}$/)
    .optional(),
  mustOfferChoices: z.boolean(),
  wantEnding: z.boolean(),
  /** The page about to be written (the opening is page 1). */
  turn: z.number().int().min(2).max(500),
  sessionId: z.string().min(8).max(64),
});

/** How many of the latest choices the prompt lists (older ones live on in the summary). */
const CHOICES_IN_PROMPT = 30;

export async function POST(request: Request) {
  const user = await currentUser();
  if (!user) return unauthorized();
  const parsed = BodySchema.safeParse(await request.json().catch(() => null));
  if (!parsed.success) {
    return Response.json({ type: "error", code: "bad_request" }, { status: 400 });
  }
  const b = parsed.data;
  const { ADVENTURE_SOFT_TURN_CAP, ADVENTURE_HARD_TURN_CAP } = env();

  return sseResponse(async (send) => {
    const incoming = [b.summary, ...b.facts, ...b.choicesSoFar, ...b.recentPages, b.choice ?? ""];
    if (incoming.some((t) => findBlocked(t))) return send({ type: "error", code: "invalid" });
    const ctx = await loadAdventureBook(b.bookId);
    if (!ctx) return send({ type: "error", code: "invalid" });

    const store = serverStore();
    const allowed = await guardGeneration(store, {
      sessionId: user.id,
      ipHash: ipHashFor(request.headers),
    });
    if (!allowed.ok) {
      return send({ type: "denied", reason: allowed.reason, retryAfterSec: allowed.retryAfterSec });
    }
    await recordGeneration(store, user.id);

    // The hard cap always forces an ending, whatever the client asks for.
    const phase = b.wantEnding || b.turn >= ADVENTURE_HARD_TURN_CAP ? "ending" : "continue";
    const beat = beatIndexFor(b.turn, ctx.outline.length, ADVENTURE_SOFT_TURN_CAP);
    const character =
      b.style && b.style !== "direct" ? ctx.cast.find((c) => c.id === b.characterId) : undefined;

    const r = await runGeneration(
      buildAdventureContinuationPrompt({
        book: ctx.book,
        synopsis: ctx.summaries.synopsis,
        cast: ctx.cast,
        character,
        summary: b.summary,
        facts: b.facts,
        choicesSoFar: b.choicesSoFar.slice(-CHOICES_IN_PROMPT),
        recentPages: b.recentPages,
        choice: b.choice,
        beat: ctx.outline[beat],
        isFinalBeat: beat === ctx.outline.length - 1,
        mustOfferChoices: b.mustOfferChoices,
        phase,
      }),
      {
        sessionId: b.sessionId,
        bookId: ctx.book.id,
        onText: (text) => send({ type: "delta", text }),
        onReset: () => send({ type: "reset" }),
        accept: (d) =>
          (phase === "ending" || !b.mustOfferChoices || d.choices.length >= 2) &&
          generatedTextIsClean(d.story, d.summary, ...d.facts, ...d.choices),
      },
    );
    if (!r) return send({ type: "error", code: "failed" });
    const isEnding = phase === "ending" || r.data.isEnding;
    send({
      type: "ready",
      story: clean(r.data.story),
      summary: clean(r.data.summary).slice(0, 1500),
      facts: r.data.facts.map(clean).filter(Boolean).slice(-MAX_FACTS),
      choices: isEnding ? [] : r.data.choices.slice(0, 3).map(clean),
      isEnding,
    });
  });
}
