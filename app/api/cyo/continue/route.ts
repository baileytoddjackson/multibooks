import { z } from "zod";
import { guardGeneration, ipHashFor, recordGeneration } from "@/lib/budget/budget";
import { GENRES, type GenreId } from "@/lib/cyo/genres";
import { env } from "@/lib/env";
import { sseResponse } from "@/lib/http/sse";
import { runGeneration } from "@/lib/llm/runGeneration";
import { buildCyoContinuationPrompt } from "@/lib/prompts/cyoContinuation";
import { findBlocked } from "@/lib/safety/blocklist";
import { generatedTextIsClean } from "@/lib/safety/moderate";
import { serverStore } from "@/lib/server-store";
import { cleanGeneratedText as clean } from "@/lib/text/clean";

/**
 * POST /api/cyo/continue → text/event-stream (same event shapes as /api/cyo/start)
 *   ready: {story, summary, choices, isEnding}
 *
 * Stateless: the client sends the compact state (summary + last segment + choice). All of it was
 * generated by us, but it passes through the browser, so it's length-limited and re-checked.
 */
const BodySchema = z.object({
  genre: z.enum(GENRES.map((g) => g.id) as [GenreId, ...GenreId[]]),
  summary: z.string().max(1500),
  lastSegment: z.string().max(4000),
  choice: z.string().max(120).optional(),
  style: z.enum(["direct", "character", "both"]).optional(),
  character: z.object({ name: z.string().max(60), oneLine: z.string().max(120) }).optional(),
  mustOfferChoices: z.boolean(),
  wantEnding: z.boolean(),
  turn: z.number().int().min(1).max(200),
  sessionId: z.string().min(8).max(64),
});

export async function POST(request: Request) {
  const parsed = BodySchema.safeParse(await request.json().catch(() => null));
  if (!parsed.success)
    return Response.json({ type: "error", code: "bad_request" }, { status: 400 });
  const b = parsed.data;
  const { CYO_HARD_TURN_CAP } = env();

  return sseResponse(async (send) => {
    if (
      [b.summary, b.lastSegment, b.choice ?? "", b.character?.name ?? ""].some((t) =>
        findBlocked(t),
      )
    ) {
      send({ type: "error", code: "invalid" });
      return;
    }
    const store = serverStore();
    const allowed = await guardGeneration(store, {
      sessionId: b.sessionId,
      ipHash: ipHashFor(request.headers),
    });
    if (!allowed.ok) {
      send({ type: "denied", reason: allowed.reason, retryAfterSec: allowed.retryAfterSec });
      return;
    }
    await recordGeneration(store, b.sessionId);

    // The hard cap always forces an ending, whatever the client asks for.
    const phase = b.wantEnding || b.turn >= CYO_HARD_TURN_CAP ? "ending" : "continue";
    const r = await runGeneration(
      buildCyoContinuationPrompt({
        genre: b.genre,
        summary: b.summary,
        lastSegment: b.lastSegment,
        choice: b.choice,
        style: b.style,
        character: b.character,
        mustOfferChoices: b.mustOfferChoices,
        phase,
      }),
      {
        sessionId: b.sessionId,
        onText: (text) => send({ type: "delta", text }),
        onReset: () => send({ type: "reset" }),
        accept: (d) =>
          (phase === "ending" || !b.mustOfferChoices || d.choices.length >= 2) &&
          generatedTextIsClean(d.story, d.summary, ...d.choices),
      },
    );
    if (!r) {
      send({ type: "error", code: "failed" });
      return;
    }
    const isEnding = phase === "ending" || r.data.isEnding;
    send({
      type: "ready",
      story: clean(r.data.story),
      summary: clean(r.data.summary).slice(0, 1200),
      choices: isEnding ? [] : r.data.choices.slice(0, 3).map(clean),
      isEnding,
    });
  });
}
